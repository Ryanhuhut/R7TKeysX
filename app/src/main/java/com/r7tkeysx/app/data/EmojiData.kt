    // Gắn màu da vào emoji nếu nó hỗ trợ; tone rỗng = màu mặc định (vàng)
    fun withTone(emoji: String, modifier: String): String {
        if (modifier.isEmpty()) return emoji
        val base = emoji.replace("️", "")
        return if (base in skinnable) base + modifier else emoji
